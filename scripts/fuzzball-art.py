#!/usr/bin/env python3
"""Turns art/pluizenbolletje.svg (the fuzzball drawn in Affinity Designer) into src/components/common/fuzzballLayers.ts.

Run it after a new export of the drawing (all layers visible, groups named):

    python3 scripts/fuzzball-art.py

The drawing is 1600x1600 with a test circle that is dropped. Layer groups at the top level: Achtergronden/<background>,
Benen, Armen, Bolletje (with Bol, Wenkbrauwen, Monden/<mouth>, Ogen/<eyes>), Attributen/<item>. A clipping mask in the
Bolletje layer belongs to an item (the top hat: the fuzz must not poke through it) and is applied only when that item is
worn; masks are matched to `MASKED` in the order they sit in the file. The oranges of the drawing become colour roles
({{light}}, {{mid}}, ...) that the component fills in per fur colour; the iris becomes {{iris}}; every red of an item
(cap, hat bands, crown gems, bow) becomes {{accent|r,g,b}}, which the component recolours in the profile's accent colour
or leaves as it is; ids get the {{id}} prefix so several fuzzballs can share a page.
"""
import colorsys, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = (ROOT / "art/pluizenbolletje.svg").read_text()
OUT = ROOT / "src/components/common/fuzzballLayers.ts"

# The original colours per role, so orange keeps the drawing's own colours.
ROLES = {
    "light": ["rgb(255,154,27)", "rgb(255,155,28)", "rgb(255,158,29)", "rgb(255,148,21)", "rgb(255,152,27)"],
    "mid": ["rgb(255,129,16)", "rgb(253,122,13)", "rgb(254,127,14)"],  # the last two: the line of the grin
    "deep": ["rgb(246,90,0)", "rgb(255,110,4)"],
    "brow": ["rgb(241,102,0)", "rgb(242,94,13)"],
    "limb": ["rgb(223,60,0)"],
    "limb2": ["rgb(232,76,0)"],
    "dark": ["rgb(99,33,0)"],
}
IRIS = "rgb(13,121,242)"
EYES = {"open": "Open-ogen", "blij": "Lachende-ogen", "knipoog": "Knipoog", "dicht": "Gesloten-ogen"}
MOUTHS = {"lach": "Lach", "open-lach": "Open-lach", "grijns": "Grijns", "tong": "Tong", "verrast": "Verbazing", "zang": "Zang"}
ITEMS = {"pet": "Pet", "bolhoed": "Bolhoed", "hoge-hoed": "Hoge-hoed", "kroon": "Kroon", "bril": "Bril", "zonnebril": "Zonnebril", "strik": "Strik"}
BACKGROUNDS = {"sterren": "Sterren", "noten": "Noten"}
# The items with a clipping mask on the ball, in the order of the masks in the Bolletje layer (outermost first).
MASKED = ["hoge-hoed"]
FIXED = ["Benen", "Armen", "Bolletje", "Bol", "Wenkbrauwen", "Ogen", "Monden"]

missing = [v for v in [*FIXED, *EYES.values(), *MOUTHS.values(), *ITEMS.values(), *BACKGROUNDS.values()] if f'<g id="{v}"' not in SRC]
if missing:
    sys.exit(f"layers missing from the export (hidden in Affinity?): {', '.join(missing)}")


def group(gid: str) -> str:
    """A layer group by id, with everything nested in it."""
    i = SRC.index(f'<g id="{gid}"')
    depth = 0
    for m in re.finditer(r"<(/?)g\b", SRC[i:]):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            return SRC[i : SRC.index(">", i + m.end()) + 1]
    raise ValueError(gid)


def opening(g: str) -> str:
    """The opening tag of a group (it carries the transform)."""
    return g[: g.index(">") + 1]


def masks() -> list[str]:
    """The clipping masks in the Bolletje layer: each clipPath with the opening tag of the group it clips, outermost first."""
    return [m.group(0) for m in re.finditer(r'<clipPath id="([^"]+)">.*?</clipPath>\s*<g clip-path="url\(#\1\)">', group("Bolletje"), re.S)]


def is_red(r: int, g: int, b: int) -> bool:
    h, _, sat = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    return sat > 0.5 and (h < 0.05 or h > 0.95)


def accent(s: str) -> str:
    """The reds of an item as {{accent|r,g,b}}: the component keeps or recolours them."""
    return re.sub(r"rgb\((\d+),(\d+),(\d+)\)", lambda m: "{{accent|" + ",".join(m.groups()) + "}}" if is_red(*map(int, m.groups())) else m.group(0), s)


def clean(s: str) -> str:
    s = re.sub(r'\s*serif:id="[^"]*"', "", s)
    s = re.sub(r"\s+", " ", s).replace("> <", "><").strip()
    for role, colours in ROLES.items():
        for c in colours:
            s = s.replace(c, "{{" + role + "}}")
    s = s.replace(IRIS, "{{iris}}")
    s = re.sub(r'id="_([A-Za-z]+\d+)"', r'id="{{id}}\1"', s)
    s = re.sub(r"#_([A-Za-z]+\d+)", r"#{{id}}\1", s)
    s = re.sub(r' id="(?!\{\{id\}\})[^"]*"', "", s)
    return s


found = masks()
if len(found) != len(MASKED):
    sys.exit(f"{len(found)} clipping masks in the Bolletje layer, but MASKED names {len(MASKED)} items")

defs = SRC[SRC.index("<defs>") : SRC.index("</defs>") + 7]
ogen, monden = opening(group("Ogen")), opening(group("Monden"))


def ts_record(name: str, parts: dict[str, str], type_: str = "", accented: bool = False) -> str:
    rows = ",\n".join(f"  {k!r}: `{accent(clean(v)) if accented else clean(v)}`" for k, v in parts.items())
    return f"export const {name}{type_} = {{\n{rows},\n}}{'' if type_ else ' as const'};\n"


out = f'''/**
 * The layers of the drawn fuzzball, generated by scripts/fuzzball-art.py from art/pluizenbolletje.svg. Do not edit:
 * change the drawing and run the script. Placeholders: {{{{id}}}} (a prefix for ids), {{{{light}}}} {{{{mid}}}} {{{{deep}}}}
 * {{{{brow}}}} {{{{limb}}}} {{{{limb2}}}} {{{{dark}}}} (the colour roles) and {{{{iris}}}}. The drawing is 1600x1600.
 */
export const FUZZBALL_SIZE = 1600;

/** Behind the body, on the disc. */
{ts_record("FUZZBALL_BACKGROUND_ART", {k: group(v) for k, v in BACKGROUNDS.items()})}
/** Gradients. */
export const FUZZBALL_DEFS = `{clean(defs)}`;

/** Legs and arms, behind the ball. */
export const FUZZBALL_LIMBS = `{clean(group("Benen") + group("Armen"))}`;

/** The open Bolletje group (it carries the transform): the ball, eyes and mouth go inside; `FUZZBALL_CLOSE` closes it. */
export const FUZZBALL_BALL_OPEN = `{clean(opening(group("Bolletje")))}`;

/** The ball and the eyebrows. */
export const FUZZBALL_BALL = `{clean(group("Bol") + group("Wenkbrauwen"))}`;
export const FUZZBALL_CLOSE = "</g>";

{ts_record("FUZZBALL_EYES_ART", {k: ogen + group(v) + "</g>" for k, v in EYES.items()})}
{ts_record("FUZZBALL_MOUTH_ART", {k: monden + group(v) + "</g>" for k, v in MOUTHS.items()})}
/** Worn on top of everything, outside the Bolletje group; their reds are {{{{accent|r,g,b}}}}. */
{ts_record("FUZZBALL_ITEM_ART", {k: group(v) for k, v in ITEMS.items()}, accented=True)}
/**
 * The clipping mask an item puts on the ball (the fuzz does not poke through the top hat): the clipPath and the opening
 * tag of the clipped group, placed right after `FUZZBALL_BALL_OPEN`; the component closes that group before
 * `FUZZBALL_CLOSE`.
 */
{ts_record("FUZZBALL_ITEM_MASK", dict(zip(MASKED, found)), ": Partial<Record<keyof typeof FUZZBALL_ITEM_ART, string>>")}'''
OUT.write_text(out)
subprocess.run(["npx", "prettier", "--log-level", "warn", "--write", str(OUT)], cwd=ROOT, check=True)
print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size} bytes")
